-- Custo.AI PostgreSQL starting schema (draft; not yet applied).
-- Requires PostgreSQL and PostGIS. Run in a dedicated database after review.

CREATE EXTENSION IF NOT EXISTS postgis;

CREATE TABLE users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(160) NOT NULL,
  email varchar(255) NOT NULL UNIQUE,
  phone varchar(40),
  password varchar(255) NOT NULL,
  email_verified_at timestamptz,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE roles (
  id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(40) NOT NULL UNIQUE
);

INSERT INTO roles (name) VALUES ('buyer'), ('seller'), ('reviewer'), ('admin');

CREATE TABLE role_user (
  user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  role_id smallint NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, role_id)
);

CREATE TABLE categories (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  parent_id bigint REFERENCES categories(id) ON DELETE SET NULL,
  name varchar(100) NOT NULL,
  slug varchar(120) NOT NULL UNIQUE,
  applies_to varchar(20) NOT NULL CHECK (applies_to IN ('business', 'listing', 'both')),
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE businesses (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_user_id bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  primary_category_id bigint REFERENCES categories(id) ON DELETE SET NULL,
  name varchar(180) NOT NULL,
  slug varchar(200) NOT NULL UNIQUE,
  description text NOT NULL,
  business_status varchar(24) NOT NULL DEFAULT 'draft'
    CHECK (business_status IN ('draft', 'pending_review', 'published', 'suspended', 'archived')),
  verification_status varchar(24) NOT NULL DEFAULT 'unsubmitted'
    CHECK (verification_status IN ('unsubmitted', 'pending', 'verified', 'changes_requested', 'rejected', 'expired')),
  verified_at timestamptz,
  verification_expires_at timestamptz,
  phone varchar(40) NOT NULL,
  whatsapp_phone varchar(40),
  website_url text,
  address_line text NOT NULL,
  neighborhood varchar(120),
  city varchar(120) NOT NULL,
  region varchar(120),
  country_code char(2) NOT NULL DEFAULT 'GH',
  currency_code char(3) NOT NULL DEFAULT 'GHS',
  location geography(Point, 4326),
  opening_hours jsonb NOT NULL DEFAULT '{}'::jsonb,
  published_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz,
  CHECK ((verification_status = 'verified' AND verified_at IS NOT NULL) OR verification_status <> 'verified'),
  CHECK ((business_status = 'published' AND published_at IS NOT NULL) OR business_status <> 'published')
);

CREATE INDEX businesses_owner_idx ON businesses(owner_user_id);
CREATE INDEX businesses_public_status_idx ON businesses(business_status, verification_status);
CREATE INDEX businesses_city_idx ON businesses(country_code, city, neighborhood);
CREATE INDEX businesses_location_gist_idx ON businesses USING gist(location);

CREATE TABLE business_categories (
  business_id bigint NOT NULL REFERENCES businesses(id) ON DELETE CASCADE,
  category_id bigint NOT NULL REFERENCES categories(id) ON DELETE RESTRICT,
  is_primary boolean NOT NULL DEFAULT false,
  PRIMARY KEY (business_id, category_id)
);

CREATE TABLE listings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  business_id bigint NOT NULL REFERENCES businesses(id) ON DELETE CASCADE,
  category_id bigint REFERENCES categories(id) ON DELETE SET NULL,
  listing_type varchar(16) NOT NULL CHECK (listing_type IN ('product', 'service')),
  title varchar(180) NOT NULL,
  slug varchar(200) NOT NULL,
  description text NOT NULL,
  keywords text,
  listing_status varchar(16) NOT NULL DEFAULT 'draft'
    CHECK (listing_status IN ('draft', 'published', 'archived')),
  price_type varchar(20) NOT NULL DEFAULT 'quote'
    CHECK (price_type IN ('fixed', 'starting_from', 'quote', 'not_listed')),
  price_amount numeric(12,2),
  currency_code char(3) NOT NULL DEFAULT 'GHS',
  availability_status varchar(20) NOT NULL DEFAULT 'unknown'
    CHECK (availability_status IN ('in_stock', 'limited', 'made_to_order', 'out_of_stock', 'unknown')),
  available_quantity integer CHECK (available_quantity IS NULL OR available_quantity >= 0),
  minimum_order_quantity integer CHECK (minimum_order_quantity IS NULL OR minimum_order_quantity > 0),
  condition varchar(16) CHECK (condition IS NULL OR condition IN ('new', 'used', 'refurbished', 'not_applicable')),
  last_confirmed_at timestamptz,
  published_at timestamptz,
  search_document tsvector GENERATED ALWAYS AS (
    to_tsvector('simple', coalesce(title, '') || ' ' || coalesce(description, '') || ' ' || coalesce(keywords, ''))
  ) STORED,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz,
  UNIQUE (business_id, slug),
  CHECK (
    (price_type IN ('fixed', 'starting_from') AND price_amount IS NOT NULL)
    OR (price_type IN ('quote', 'not_listed') AND price_amount IS NULL)
  ),
  CHECK ((listing_status = 'published' AND published_at IS NOT NULL) OR listing_status <> 'published')
);

CREATE INDEX listings_business_idx ON listings(business_id, listing_status);
CREATE INDEX listings_category_idx ON listings(category_id, listing_status);
CREATE INDEX listings_price_idx ON listings(currency_code, price_amount) WHERE listing_status = 'published';
CREATE INDEX listings_availability_idx ON listings(availability_status, last_confirmed_at) WHERE listing_status = 'published';
CREATE INDEX listings_search_gin_idx ON listings USING gin(search_document);

CREATE TABLE media (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  business_id bigint NOT NULL REFERENCES businesses(id) ON DELETE CASCADE,
  listing_id bigint REFERENCES listings(id) ON DELETE CASCADE,
  uploaded_by_user_id bigint REFERENCES users(id) ON DELETE SET NULL,
  purpose varchar(24) NOT NULL CHECK (purpose IN ('logo', 'business_gallery', 'listing_image', 'verification_document')),
  storage_disk varchar(60) NOT NULL,
  storage_key text NOT NULL UNIQUE,
  original_filename varchar(255),
  mime_type varchar(120) NOT NULL,
  byte_size bigint NOT NULL CHECK (byte_size > 0),
  is_public boolean NOT NULL DEFAULT false,
  sort_order smallint NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (purpose <> 'verification_document' OR is_public = false),
  CHECK (purpose <> 'listing_image' OR listing_id IS NOT NULL)
);

CREATE INDEX media_business_purpose_idx ON media(business_id, purpose, sort_order);
CREATE INDEX media_listing_idx ON media(listing_id, sort_order) WHERE listing_id IS NOT NULL;

CREATE TABLE verification_submissions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  business_id bigint NOT NULL REFERENCES businesses(id) ON DELETE CASCADE,
  submitted_by_user_id bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  status varchar(24) NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'approved', 'rejected', 'changes_requested')),
  seller_note text,
  reviewer_user_id bigint REFERENCES users(id) ON DELETE RESTRICT,
  reviewer_note text,
  submitted_at timestamptz NOT NULL DEFAULT now(),
  reviewed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (
    (status = 'pending' AND reviewed_at IS NULL)
    OR (status <> 'pending' AND reviewed_at IS NOT NULL AND reviewer_user_id IS NOT NULL)
  )
);

CREATE INDEX verification_queue_idx ON verification_submissions(status, submitted_at);
CREATE INDEX verification_business_idx ON verification_submissions(business_id, submitted_at DESC);

CREATE TABLE verification_documents (
  submission_id bigint NOT NULL REFERENCES verification_submissions(id) ON DELETE CASCADE,
  media_id bigint NOT NULL UNIQUE REFERENCES media(id) ON DELETE RESTRICT,
  document_type varchar(60) NOT NULL,
  PRIMARY KEY (submission_id, media_id)
);

